-- My Account: stable social-login identities, pending email changes and the
-- atomic email-change confirmation. All objects are only reached through the
-- service-role key; RLS is enabled with no policies so anon/authenticated
-- clients cannot read token hashes.

-- 1. Social-login identities --------------------------------------------------
-- users.provider/"providerAccountId" only hold the last provider used, so a
-- user who changes their email could not be found again by the provider they
-- did not use last. Each (provider, provider_account_id) maps to one user.
create table if not exists public.user_oauth_accounts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  provider text not null check (provider in ('google', 'facebook')),
  provider_account_id text not null,
  created_at timestamptz not null default now(),
  unique (provider, provider_account_id)
);

create index if not exists user_oauth_accounts_user_idx on public.user_oauth_accounts(user_id);

alter table public.user_oauth_accounts enable row level security;

insert into public.user_oauth_accounts (user_id, provider, provider_account_id)
select id, provider, "providerAccountId"
from public.users
where provider in ('google', 'facebook')
  and "providerAccountId" is not null
on conflict (provider, provider_account_id) do nothing;

-- 2. Pending email changes ----------------------------------------------------
-- One row per user: a newer request replaces the previous token, which
-- invalidates the older link. Only a SHA-256 hash of the token is stored. A
-- confirmed or expired-and-attempted request is deleted.
create table if not exists public.email_change_requests (
  user_id bigint primary key references public.users(id) on delete cascade,
  new_email text not null,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.email_change_requests enable row level security;

-- 3. Atomic confirmation ------------------------------------------------------
-- Consumes the token (DELETE ... RETURNING, so a concurrent second call finds
-- nothing), re-checks that no other account uses the address
-- (case-insensitive, serialised per address with an advisory lock) and
-- updates users.email in the same transaction. It only ever locks the
-- caller's own request row and users row.
-- Returns one row: status in ('confirmed', 'invalid', 'expired', 'email_taken').
create or replace function public.confirm_email_change(p_user_id bigint, p_token_hash text)
returns table (status text, old_email text, new_email text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.email_change_requests%rowtype;
  v_old_email text;
begin
  delete from public.email_change_requests r
  where r.user_id = p_user_id
    and r.token_hash = p_token_hash
  returning r.* into v_request;

  if not found then
    return query select 'invalid'::text, null::text, null::text;
    return;
  end if;

  if v_request.expires_at < now() then
    return query select 'expired'::text, null::text, null::text;
    return;
  end if;

  perform pg_advisory_xact_lock(hashtextextended(lower(v_request.new_email), 0));

  if exists (
    select 1 from public.users u
    where lower(u.email) = lower(v_request.new_email)
      and u.id <> p_user_id
  ) then
    return query select 'email_taken'::text, null::text, null::text;
    return;
  end if;

  select u.email into v_old_email
  from public.users u
  where u.id = p_user_id
  for update;

  if not found then
    return query select 'invalid'::text, null::text, null::text;
    return;
  end if;

  begin
    update public.users set email = v_request.new_email where id = p_user_id;
  exception when unique_violation then
    return query select 'email_taken'::text, null::text, null::text;
    return;
  end;

  -- Other users' pending requests for this address are deliberately left in
  -- place: deleting them here would lock rows a concurrent confirmation may
  -- already hold while it waits on the advisory lock above (deadlock). They
  -- fail with 'email_taken' when confirmed.

  return query select 'confirmed'::text, v_old_email, v_request.new_email;
end;
$$;

revoke all on function public.confirm_email_change(bigint, text) from public, anon, authenticated;
grant execute on function public.confirm_email_change(bigint, text) to service_role;

-- 4. Table privileges ---------------------------------------------------------
-- Supabase's default privileges give anon and authenticated every privilege
-- on new tables. RLS hides the rows, but it does not govern TRUNCATE,
-- REFERENCES or TRIGGER, and grants also publish the columns in the API
-- description. The application only reaches these tables server-side with
-- the service_role key (and through confirm_email_change() above, which runs
-- as its owner), so API roles get nothing and service_role gets exactly what
-- the routes use.
revoke all on table public.user_oauth_accounts   from public, anon, authenticated;
revoke all on table public.email_change_requests from public, anon, authenticated;
revoke all on sequence public.user_oauth_accounts_id_seq from public, anon, authenticated;

revoke all on table public.user_oauth_accounts   from service_role;
revoke all on table public.email_change_requests from service_role;
revoke all on sequence public.user_oauth_accounts_id_seq from service_role;
grant select, insert, update, delete on table public.user_oauth_accounts   to service_role;
grant select, insert, update, delete on table public.email_change_requests to service_role;
